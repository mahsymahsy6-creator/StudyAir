export const TRANSLATIONS = translations;

export function t(key: keyof typeof translations["en"], params?: Record<string, string | number>): string {
  const dict = translations[currentLanguage] || translations["id"];
  let str: string = (dict as any)[key] || (translations["en"] as any)[key] || key;
  if (params) {
    for (const [pKey, pVal] of Object.entries(params)) {
      str = str.replace(new RegExp(`\\{${pKey}\\}`, "g"), String(pVal));
    }
  }
  return str;
}
